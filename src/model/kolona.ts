/**
 * КОЛОНАТА · какво е една колона на таблица, като ДАННИ (ADR-003).
 *
 * Видът живее в КОЛОНАТА, не в цифрата (ADR-014 на MasterBook, пренесен).
 * Оттук се извежда всичко останало: кой СЛОТ носи клетката в събитието, как
 * се показва, влиза ли в сбор, как се пише в Книгата.
 */

import type { VidStoynost } from './vid-stoynost.js';

/**
 * Видът на колоната · петте вида стойност плюс три, които са ВРЪЗКИ, не стойности:
 *
 *   · `izbor`       — падащо меню от номенклатура · клетката пази НОМЕРА на стойността;
 *   · `vrazka`      — ред от друга таблица (Обект → Имот) · клетката пази id-то му;
 *   · `nomeratsiya` — сметнатата номерация (`3.1.1.27`) · ЗАТВОРЕНА, никой не я пише.
 */
export type VidKolona = VidStoynost | 'izbor' | 'vrazka' | 'nomeratsiya';

/**
 * СТРАНАТА на един ред с пари · приходът е +, разходът е − (правило 20).
 * Колоната, която носи секция, казва на коя страна е тя; знакът на сумата и
 * страната на секцията ТРЯБВА да си съответстват, и това е предусловие.
 */
export type Strana = 'prihod' | 'razhod';

/** Слотът в събитието · ТОЧНО един на клетка · по вида на колоната. */
export type Slot = 'tekst' | 'chislo' | 'stoynost_st' | 'nomer';

export interface Kolona {
  readonly klyuch: string;
  /** главата · дословно както е в Книгата, или НАША дума, ако Книгата я няма */
  readonly ime: string;
  readonly vid: VidKolona;
  /** ключът на номенклатурата · само при `izbor` */
  readonly nomenklatura?: string;
  /**
   * таблиците, към които може да сочи · само при `vrazka` · коя точно казва
   * ПРЕФИКСЪТ на id-то (`imot:` · `obekt:` · `biznes:`), защото `idNaRed` го носи;
   * Обектът сочи само Имот (`['imoti']`), Задачата — Имот, Обект или Бизнес
   */
  readonly vrazka?: readonly string[];
  /**
   * Връзка, която САМО СОЧИ · не прави реда ДЕТЕ на посочения.
   *
   * Отговорникът на задача сочи човек, но задачата не е негово дете: човек, който
   * напуска, се изключва, а задачите му остават и се КАЗВАТ (ADR-009). Без този
   * белег правилото „ред с живи деца не се изключва" би заключило всеки служител,
   * който носи макар една задача, и съобщението („изключи първо тях") би било
   * грешен съвет — вярното е да им дадеш друг отговорник.
   */
  readonly samoSochi?: true;
  /** за `izbor` с номерация по белег · кой белег се взима от коя колона на същия ред */
  readonly belegOt?: string;
  /** колоната носи СЕКЦИЯ на тази страна · точно една такава колона е пълна на ред */
  readonly strana?: Strana;
  readonly zadalzhitelna: boolean;
  /** затворена = сметка или пренесено · не се редактира от никого (правило 18) */
  readonly zatvorena: boolean;
  /** мярката на числото · кв. см за площ; иначе цяло число */
  readonly merka?: 'kvsm';
  /** думата ни е, не негова · за износа и за Заданието (правило 17) */
  readonly nashaDuma?: boolean;
  /** кратка дума за разписките и екрана, когато главата му е дълга · главата остава негова */
  readonly kratko?: string;
  /**
   * КЛЮЧЪТ на ред без номерация · тези колони заедно казват „същият ред ли е":
   * задачата е родител · вид · име · начало; движението — родител · име · секция ·
   * функция · месец. Изрично, не по „задължителна": иначе Оценката щеше да влезе
   * в ключа на задачата, а сумата — в ключа на движението (поправката щеше да
   * ражда нов ред вместо да поправя стария).
   */
  readonly vKlyucha?: true;
}

/** Кой слот носи клетката на тази колона · `undefined` за затворените. */
export function slotNaKolonata(k: Kolona): Slot | undefined {
  if (k.zatvorena) return undefined;
  switch (k.vid) {
    case 'evro':
      return 'stoynost_st';
    case 'chislo':
    case 'protsent':
      return 'chislo';
    case 'izbor':
      return 'nomer';
    case 'tekst':
    case 'data':
    case 'vrazka':
      return 'tekst';
    case 'nomeratsiya':
      return undefined;
  }
}

/** Колоната влиза ли в сбор · само еврото (правило 3 · ADR-014). */
export function vlizaVSbor(k: Kolona): boolean {
  return k.vid === 'evro' && !k.zatvorena;
}
