import type { OpisNaList, ProchetenList } from '../../src/kniga/ooxml.ts';

export function opisOtProcheten(l: ProchetenList): OpisNaList {
  return {
    ime: l.ime,
    redove: l.kletki.map((r) => [...r]),
    skritiKoloni: [...l.skritiKoloni],
    skrit: l.skrit,
  };
}
