/**
 * КАЛЕНДАРЪТ НА ПРОХОДА · дати, които не менят присъдата с деня на пускане.
 *
 * Проходът гледа ЖИВИЯ екран, а екранът смята прозорци от ДНЕС: тактът на Ганта
 * е дванайсет месеца около текущия, а листът Сметки реже колоните си от
 * предишния месец нататък. Дата, взета „днес + 5 дни", пада ту в един месец, ту
 * в два — и очакване, заковано на едно ■, става ту вярно, ту невярно.
 *
 * Намерено на 06.09 (по негов въпрос за скритите дефекти): задачата на §3 се
 * пишеше с „днес + 5" и „днес + 9". В около четири дни на месец двете падат в
 * РАЗЛИЧНИ месеца — проходът пада на всяко осмо пускане, без нито един ред
 * променен код. А фиксираният месец „2026-09" щеше да спре да работи изобщо
 * след 01.11.2026, защото излиза извън прозореца на листа.
 *
 * ЛЕКЪТ: всички дати се раждат от ЕДИН ден-котва — десетият на ТЕКУЩИЯ месец.
 * Той е достатъчно навътре, за да събере период от няколко дни, без да го
 * пренесе в следващия месец, и се мести с календара, вместо да остарява.
 */

/** Месецът, в който проходът работи · винаги текущият (ГГГГ-ММ). */
export function mesetsatNaProhoda(): string {
  return new Date().toISOString().slice(0, 7);
}

/**
 * Ден от текущия месец · `den` е числото на деня (1–28).
 *
 * До 28, защото февруари: 29-и не съществува всяка година, а проходът не бива
 * да зависи от това коя е.
 */
export function denOtMesetsa(den: number): string {
  if (den < 1 || den > 28) throw new RangeError(`Денят е между 1 и 28; получено: ${den}`);
  return `${mesetsatNaProhoda()}-${String(den).padStart(2, '0')}`;
}
